export function getCuratedPhotos(slug: string): CuratedPhoto[] {
  if (!slug || !Object.hasOwn(CURATED_CAFE_PHOTOS, slug)) return [];
  const photos = CURATED_CAFE_PHOTOS[slug];
  return Array.isArray(photos) ? photos.map((p) => ({ ...p })) : [];
}

export function getCuratedCover(slug: string): string | null {
  if (!slug || !Object.hasOwn(CURATED_CAFE_PHOTOS, slug)) return null;
  const photos = CURATED_CAFE_PHOTOS[slug];
  if (!Array.isArray(photos) || photos.length === 0) return null;
  const cover = photos.find((p) => p.isCover) ?? photos[0];
  return cover?.url ?? null;
}
